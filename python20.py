dia = int(input("Digite um número (1 a 7):"))#perguntando um número

if dia == 1:#se dia for igual a 1 exibe o resultado
    print("Domingo")

elif dia == 2:#se dia for igual a 2 exibe o resultado
    print("Segunda-feira")

elif dia == 3:#se dia for igual a 3 exibe o resultado
    print("Terça-feira")

elif dia == 4:#se dia for igual a 4 exibe o resultado
    print("Quarta-feira")

elif dia == 5:#se dia for igual a 5 exibe o resultado
    print("Quinta-feira")

elif dia == 6:#se dia for igual a 6 exibe o resultado
    print("Sexta-feira")

elif dia == 7:#se dia for igual a 7 exibe o resultado
    print("Sábado")

else:#qualquer outro numero e invalido
    print("Dia inválido")