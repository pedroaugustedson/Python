n1 = int(input("Digite o primeiro número")) #Perguntando o primeiro numero e guardando na variavel n1
n2 = int(input("Digite o segundo número")) #Perguntando o segundo numero e guardando na variavel n2

if n1 == n2:#se n1 for igual a n2 o resultado é os numeros sao iguais
    print("Os números são iguias")

elif n1 > n2:#se n1 for maior que n2 o resultado o maior é n1
    print("O maior é", n1)

else:#se n2 for maior que n1 o resultado o maior é n2
    print("O maior é", n2)